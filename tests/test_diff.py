"""Tests for the schema diff."""

from __future__ import annotations

from korbase._diff import diff, render
from korbase._schema import Column, ForeignKey, Index, Snapshot, Table


def col(name: str, type: str = "text", nullable: bool = True, default: str | None = None, identity: bool = False):
    """Build a column."""
    return Column(name, type, nullable, default, identity)


def tbl(name: str, columns: tuple[Column, ...], **kw) -> Table:
    """Build a table, with an `id` primary key unless told otherwise."""
    kw.setdefault("pk", ("id",))
    kw.setdefault("pk_name", f"{name}_pkey")
    return Table(name, columns, **kw)


def snap(*tables: Table) -> Snapshot:
    """Build a snapshot."""
    return Snapshot({t.name: t for t in tables})


ID = col("id", "bigint", False)
BASE = tbl("a", (ID, col("x")))


def sql_of(current: Snapshot, desired: Snapshot) -> str:
    """Return the rendered diff."""
    return render(diff(current, desired))


def test_noop():
    assert diff(snap(BASE), snap(BASE)) == []
    assert render([]) == ""


def test_create_table():
    t = tbl(
        "a",
        (col("id", "bigint", False, identity=True), col("n", "integer", False, "0")),
        uniques=(("a_n_key", ("n",)),),
    )
    assert sql_of(snap(), snap(t)) == (
        'CREATE TABLE "a" (\n    "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n'
        '    "n" integer NOT NULL DEFAULT 0,\n    CONSTRAINT "a_pkey" PRIMARY KEY ("id"),\n'
        '    CONSTRAINT "a_n_key" UNIQUE ("n")\n);\n'
    )


def test_drop_table():
    assert sql_of(snap(BASE), snap()) == ('-- korbase:review drops table a, its data is lost\nDROP TABLE "a";\n')


def test_add_column():
    new = tbl("a", (ID, col("x"), col("y", "integer", False, "1")))
    assert sql_of(snap(BASE), snap(new)) == 'ALTER TABLE "a" ADD COLUMN "y" integer NOT NULL DEFAULT 1;\n'


def test_drop_column():
    new = tbl("a", (ID,))
    assert sql_of(snap(BASE), snap(new)) == (
        '-- korbase:review drops column a.x, its data is lost\nALTER TABLE "a" DROP COLUMN "x";\n'
    )


def test_type_change():
    new = tbl("a", (ID, col("x", "integer")))
    assert sql_of(snap(BASE), snap(new)) == (
        "-- korbase:review type of a.x changes from text to integer\n"
        'ALTER TABLE "a" ALTER COLUMN "x" TYPE integer USING "x"::integer;\n'
    )


def test_nullability():
    nn = tbl("a", (ID, col("x", nullable=False)))
    assert sql_of(snap(BASE), snap(nn)) == (
        '-- korbase:review a.x becomes NOT NULL, fails if NULLs exist\nALTER TABLE "a" ALTER COLUMN "x" SET NOT NULL;\n'
    )
    assert sql_of(snap(nn), snap(BASE)) == 'ALTER TABLE "a" ALTER COLUMN "x" DROP NOT NULL;\n'


def test_default():
    d = tbl("a", (ID, col("x", default="'hi'::text")))
    assert sql_of(snap(BASE), snap(d)) == 'ALTER TABLE "a" ALTER COLUMN "x" SET DEFAULT \'hi\'::text;\n'
    assert sql_of(snap(d), snap(BASE)) == 'ALTER TABLE "a" ALTER COLUMN "x" DROP DEFAULT;\n'


def test_identity():
    ident = tbl("a", (col("id", "bigint", False, identity=True), col("x")))
    assert sql_of(snap(BASE), snap(ident)) == (
        "-- korbase:review identity of a.id changes\n"
        'ALTER TABLE "a" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY;\n'
    )
    assert "DROP IDENTITY;" in sql_of(snap(ident), snap(BASE))


def test_pk():
    none = tbl("a", (ID, col("x")), pk=None, pk_name=None)
    assert sql_of(snap(none), snap(BASE)) == 'ALTER TABLE "a" ADD CONSTRAINT "a_pkey" PRIMARY KEY ("id");\n'
    assert sql_of(snap(BASE), snap(none)) == 'ALTER TABLE "a" DROP CONSTRAINT "a_pkey";\n'
    other = tbl("a", (ID, col("x")), pk=("id", "x"))
    assert sql_of(snap(BASE), snap(other)) == (
        '-- korbase:review primary key of a changes\nALTER TABLE "a" DROP CONSTRAINT "a_pkey";\n'
        'ALTER TABLE "a" ADD CONSTRAINT "a_pkey" PRIMARY KEY ("id", "x");\n'
    )


def test_unique():
    u = tbl("a", (ID, col("x")), uniques=(("a_x_key", ("x",)),))
    assert sql_of(snap(BASE), snap(u)) == 'ALTER TABLE "a" ADD CONSTRAINT "a_x_key" UNIQUE ("x");\n'
    assert sql_of(snap(u), snap(BASE)) == 'ALTER TABLE "a" DROP CONSTRAINT "a_x_key";\n'


FK = ForeignKey("a_x_fkey", ("x",), "b", ("id",), "cascade")
B = tbl("b", (ID,))


def test_fk_add_drop_change():
    fk = tbl("a", (ID, col("x")), foreign_keys=(FK,))
    add = 'ALTER TABLE "a" ADD CONSTRAINT "a_x_fkey" FOREIGN KEY ("x") REFERENCES "b" ("id") ON DELETE CASCADE;\n'
    assert sql_of(snap(BASE, B), snap(fk, B)) == add
    assert sql_of(snap(fk, B), snap(BASE, B)) == 'ALTER TABLE "a" DROP CONSTRAINT "a_x_fkey";\n'
    nul = tbl("a", (ID, col("x")), foreign_keys=(ForeignKey("a_x_fkey", ("x",), "b", ("id",), "set null"),))
    assert sql_of(snap(fk, B), snap(nul, B)) == (
        'ALTER TABLE "a" DROP CONSTRAINT "a_x_fkey";\n' + add.replace("CASCADE", "SET NULL")
    )


def test_index():
    ix = tbl("a", (ID, col("x")), indexes=(Index("a_x_idx", ("x",), False),))
    uq = tbl("a", (ID, col("x")), indexes=(Index("a_x_idx", ("x",), True),))
    assert sql_of(snap(BASE), snap(ix)) == 'CREATE INDEX "a_x_idx" ON "a" ("x");\n'
    assert sql_of(snap(ix), snap(BASE)) == (
        '-- korbase:review index not managed by korbase or removed from the models\nDROP INDEX "a_x_idx";\n'
    )
    assert sql_of(snap(ix), snap(uq)) == 'DROP INDEX "a_x_idx";\nCREATE UNIQUE INDEX "a_x_idx" ON "a" ("x");\n'


def test_order_fks_between_new_tables():
    a = tbl("a", (ID, col("x")), foreign_keys=(FK,), indexes=(Index("a_i", ("x",), False),))
    b = tbl("b", (ID,), foreign_keys=(ForeignKey("b_id_fkey", ("id",), "a", ("id",), "cascade"),))
    lines = sql_of(snap(), snap(a, b)).split(";\n")
    kinds = [s.split(" (")[0].split(" ON")[0][:12] for s in lines if s]
    assert kinds[:2] == ["CREATE TABLE", "CREATE TABLE"]
    assert all("FOREIGN KEY" in s for s in lines[2:4])
    assert lines[4].startswith("CREATE INDEX")


def test_order_drops_last():
    fk = tbl("a", (ID, col("x")), foreign_keys=(FK,))
    out = sql_of(snap(fk, B), snap(tbl("c", (ID,))))
    pos = [out.index(s) for s in ('DROP CONSTRAINT "a_x_fkey"', 'DROP TABLE "a"', 'DROP TABLE "b"')]
    assert pos == sorted(pos)
    assert out.index("CREATE TABLE") < pos[0]


def test_rename_hint():
    new = tbl("a", (ID, col("y")))
    out = sql_of(snap(BASE), snap(new))
    hint = '-- possible rename: rewrite as ALTER TABLE "a" RENAME COLUMN "x" TO "y"\n'
    assert out == (
        hint + 'ALTER TABLE "a" ADD COLUMN "y" text;\n'
        "-- korbase:review drops column a.x, its data is lost\n" + hint + 'ALTER TABLE "a" DROP COLUMN "x";\n'
    )


def test_deterministic():
    tables = [tbl(n, (ID, col("x"))) for n in "dcba"]
    first = sql_of(snap(), snap(*tables))
    assert first == sql_of(snap(), snap(*reversed(tables)))
    assert first.index('"a"') < first.index('"b"') < first.index('"c"')


def test_pk_change_drops_and_readds_dependent_fks():
    fk = ForeignKey("c_a_fkey", ("a_id",), "a", ("id",), "no action")
    c = tbl("c", (ID, col("a_id", "bigint")), foreign_keys=(fk,))
    old_a = tbl("a", (ID, col("x", "text", False)))
    new_a = tbl("a", (ID, col("x", "text", False)), pk=("x",))
    assert sql_of(snap(old_a, c), snap(new_a, c)) == (
        'ALTER TABLE "c" DROP CONSTRAINT "c_a_fkey";\n'
        "-- korbase:review primary key of a changes\n"
        'ALTER TABLE "a" DROP CONSTRAINT "a_pkey";\n'
        'ALTER TABLE "a" ADD CONSTRAINT "a_pkey" PRIMARY KEY ("x");\n'
        'ALTER TABLE "c" ADD CONSTRAINT "c_a_fkey" FOREIGN KEY ("a_id") REFERENCES "a" ("id") ON DELETE NO ACTION;\n'
    )


def test_pk_change_dependent_fk_removed_is_not_readded():
    fk = ForeignKey("c_a_fkey", ("a_id",), "a", ("id",), "no action")
    c = tbl("c", (ID, col("a_id", "bigint")), foreign_keys=(fk,))
    c2 = tbl("c", (ID, col("a_id", "bigint")))
    new_a = tbl("a", (ID, col("x", "text", False)), pk=("x",))
    out = sql_of(snap(BASE, c), snap(new_a, c2))
    assert out.count('DROP CONSTRAINT "c_a_fkey"') == 1
    assert 'ADD CONSTRAINT "c_a_fkey"' not in out


def test_type_change_with_default():
    old = tbl("a", (ID, col("v", "text", True, "'x'")))
    new = tbl("a", (ID, col("v", "integer", True, "0")))
    assert sql_of(snap(old), snap(new)) == (
        'ALTER TABLE "a" ALTER COLUMN "v" DROP DEFAULT;\n'
        "-- korbase:review type of a.v changes from text to integer\n"
        'ALTER TABLE "a" ALTER COLUMN "v" TYPE integer USING "v"::integer;\n'
        'ALTER TABLE "a" ALTER COLUMN "v" SET DEFAULT 0;\n'
    )


def test_type_change_dropping_default():
    old = tbl("a", (ID, col("v", "text", True, "'x'")))
    new = tbl("a", (ID, col("v", "integer")))
    out = sql_of(snap(old), snap(new))
    assert out.count("DROP DEFAULT") == 1
    assert "SET DEFAULT" not in out
    assert out.index("DROP DEFAULT") < out.index("TYPE integer")


def test_drop_index_review():
    old = tbl("a", (ID, col("x")), indexes=(Index("a_x_idx", ("x",), False),))
    assert sql_of(snap(old), snap(BASE)) == (
        '-- korbase:review index not managed by korbase or removed from the models\nDROP INDEX "a_x_idx";\n'
    )


def test_add_not_null_column_without_default_review():
    new = tbl("a", (ID, col("x"), col("y", "integer", False)))
    assert sql_of(snap(BASE), snap(new)) == (
        "-- korbase:review NOT NULL column without default fails on a non-empty table\n"
        'ALTER TABLE "a" ADD COLUMN "y" integer NOT NULL;\n'
    )
