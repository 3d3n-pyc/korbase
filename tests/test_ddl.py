SCHEMA = "korbase_test_ddl"


class Color(enum.Enum):
    """An enum stored as text."""

    RED = "red"


@table("things", indexes=(Index("name", unique=True), Index("name", "qty", name="things_custom")))
@dataclass
class Thing:
    """A table with every type."""

    id: Annotated[int, PK()]
    name: Annotated[str, SqlType("varchar(80)"), Unique()]
    price: Annotated[Decimal, SqlType("numeric(10, 2)"), Default(0)]
    qty: Annotated[int, Default(5)]
    ratio: float | None
    ok: Annotated[bool, Default(True)]
    raw: bytes
    uid: uuid.UUID
    at: Annotated[datetime.datetime, Default(sql="now()")]
    day: datetime.date
    clock: datetime.time
    meta: dict[str, Any]
    tags: list[str]
    color: Color
    note: Annotated[str, Default("it's")]


@table("links")
@dataclass
class Link:
    """A composite key and a cascading foreign key."""

    thing_id: Annotated[int, PK(), FK("things.id", "cascade")]
    other: Annotated[int, PK()]


@table("bad")
@dataclass
class Bad:
    """A model with a type that has no mapping."""

    id: Annotated[int, PK()]
    thing: complex


def test_render_literal() -> None:
    """Literals render as SQL; unsupported values are refused."""
    assert render_literal(None) == "NULL"
    assert render_literal(True) == "TRUE"
    assert render_literal(False) == "FALSE"
    assert render_literal(3) == "3"
    assert render_literal(1.5) == "1.5"
    assert render_literal("it's") == "E'it''s'"
    assert render_literal("a\\b") == "E'a\\\\b'"
    with pytest.raises(KorbaseError):
        render_literal("a\x00b")
    for bad in (float("nan"), float("inf"), b"x"):
        with pytest.raises(KorbaseError):
            render_literal(bad)


def test_create_table_sql_exact() -> None:
    """The statements for a table are exact."""
    stmts = create_table_sql(table_meta(Thing))
    assert stmts[0] == (
        'CREATE TABLE "things" (\n'
        '    "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n'
        '    "name" varchar(80) NOT NULL,\n'
        '    "price" numeric(10, 2) NOT NULL DEFAULT 0,\n'
        '    "qty" bigint NOT NULL DEFAULT 5,\n'
        '    "ratio" double precision,\n'
        '    "ok" boolean NOT NULL DEFAULT TRUE,\n'
        '    "raw" bytea NOT NULL,\n'
        '    "uid" uuid NOT NULL,\n'
        '    "at" timestamptz NOT NULL DEFAULT now(),\n'
        '    "day" date NOT NULL,\n'
        '    "clock" time NOT NULL,\n'
        '    "meta" jsonb NOT NULL,\n'
        '    "tags" jsonb NOT NULL,\n'
        '    "color" text NOT NULL,\n'
        "    \"note\" text NOT NULL DEFAULT E'it''s',\n"
        '    CONSTRAINT "things_pkey" PRIMARY KEY ("id"),\n'
        '    CONSTRAINT "things_name_key" UNIQUE ("name")\n'
        ")"
    )
    assert stmts[1:] == [
        'CREATE UNIQUE INDEX "things_name_idx" ON "things" ("name")',
        'CREATE INDEX "things_custom" ON "things" ("name", "qty")',
    ]


def test_create_all_sql_order() -> None:
    """Tables come first, then foreign keys, then indexes."""
    stmts = create_all_sql([Thing, Link])
    assert [s.split(" (")[0] for s in stmts[:2]] == ['CREATE TABLE "links"', 'CREATE TABLE "things"']
    assert stmts[2] == (
        'ALTER TABLE "links" ADD CONSTRAINT "links_thing_id_fkey" FOREIGN KEY ("thing_id") '
        'REFERENCES "things" ("id") ON DELETE CASCADE'
    )
    assert stmts[3].startswith("CREATE UNIQUE INDEX")
    assert 'PRIMARY KEY ("thing_id", "other")' in stmts[0]
    assert create_all_sql([Link, Thing]) == stmts


def test_unmapped_type() -> None:
    """An unknown Python type asks for a SqlType."""
    with pytest.raises(KorbaseError, match="SqlType"):
        create_table_sql(table_meta(Bad))


def _run(dsn: str) -> None:
    """Create the models in a fresh schema and check the inspected snapshot."""

    async def main() -> None:
        pool = await AsyncpgBackend().connect(dsn)
        try:
            async with pool.acquire() as conn:
                await conn.execute_script(f"DROP SCHEMA IF EXISTS {SCHEMA} CASCADE; CREATE SCHEMA {SCHEMA}")
                try:
                    async with conn.transaction():
                        await create_all(conn, [Thing, Link], SCHEMA)
                    snap = await inspect(conn, SCHEMA)
                finally:
                    await conn.execute_script(f"DROP SCHEMA IF EXISTS {SCHEMA} CASCADE")
        finally:
            await pool.close()
        check(snap)

    asyncio.run(main())


def check(snap: Any) -> None:
    """Assert the inspected snapshot matches the models."""
    things, links = snap.tables["things"], snap.tables["links"]
    types = {c.name: (c.type, c.nullable, c.default, c.identity) for c in things.columns}
    assert types == {
        "id": ("bigint", False, None, True),
        "name": ("character varying(80)", False, None, False),
        "price": ("numeric(10,2)", False, "0", False),
        "qty": ("bigint", False, "5", False),
        "ratio": ("double precision", True, None, False),
        "ok": ("boolean", False, "true", False),
        "raw": ("bytea", False, None, False),
        "uid": ("uuid", False, None, False),
        "at": ("timestamp with time zone", False, "now()", False),
        "day": ("date", False, None, False),
        "clock": ("time without time zone", False, None, False),
        "meta": ("jsonb", False, None, False),
        "tags": ("jsonb", False, None, False),
        "color": ("text", False, None, False),
        "note": ("text", False, "'it''s'::text", False),
    }
    assert things.pk == ("id",) and things.pk_name == "things_pkey"
    assert things.uniques == (("things_name_key", ("name",)),)
    assert [(i.name, i.columns, i.unique) for i in things.indexes] == [
        ("things_custom", ("name", "qty"), False),
        ("things_name_idx", ("name",), True),
    ]
    assert links.pk == ("thing_id", "other") and links.pk_name == "links_pkey"
    fk = links.foreign_keys[0]
    assert (fk.name, fk.columns, fk.target_table, fk.target_columns, fk.on_delete) == (
        "links_thing_id_fkey",
        ("thing_id",),
        "things",
        ("id",),
        "CASCADE",
    )


def test_create_all_on_postgres(dsn: str) -> None:
    """The generated DDL runs and inspects back to what the models say."""
    _run(dsn)


@table("lit_things")
@dataclass
class LitThing:
    """A table whose default holds a backslash and a quote, with an enum from public."""

    id: Annotated[int, PK()]
    note: Annotated[str, Default("a\\'; DROP TABLE x; --")]
    mood: Annotated[str, SqlType("korbase_test_mood")]


def test_literal_safe_without_standard_conforming_strings(dsn: str) -> None:
    """Defaults stay one literal with the setting off; public types resolve."""

    async def main() -> str:
        pool = await AsyncpgBackend().connect(dsn)
        try:
            async with pool.acquire() as conn:
                await conn.execute_script(
                    f"DROP SCHEMA IF EXISTS {SCHEMA} CASCADE; DROP TYPE IF EXISTS public.korbase_test_mood;"
                    f" CREATE TYPE public.korbase_test_mood AS ENUM ('ok'); CREATE SCHEMA {SCHEMA}"
                )
                try:
                    async with conn.transaction():
                        await conn.execute_script("SET LOCAL standard_conforming_strings = off")
                        await create_all(conn, [LitThing], SCHEMA)
                    rows = await conn.fetch(
                        "SELECT column_default FROM information_schema.columns"
                        " WHERE table_schema = $1 AND table_name = 'lit_things' AND column_name = 'note'",
                        [SCHEMA],
                        lambda r: r[0],
                    )
                    return await conn.fetchrow(f"SELECT ({rows[0]})::text", [], lambda r: r[0]) or ""
                finally:
                    await conn.execute_script(
                        f"DROP SCHEMA IF EXISTS {SCHEMA} CASCADE; DROP TYPE public.korbase_test_mood"
                    )
        finally:
            await pool.close()

    assert asyncio.run(main()) == "a\\'; DROP TABLE x; --"


def test_render_literal_sqlite() -> None:
    """SQLite literals: bools are 0/1, only the single quote is doubled."""
    assert render_literal(True, SQLITE) == "1"
    assert render_literal(False, SQLITE) == "0"
    assert render_literal("it's", SQLITE) == "'it''s'"
    assert render_literal("a\\b", SQLITE) == "'a\\b'"
    assert render_literal(3, SQLITE) == "3"
    assert render_literal(1.5, SQLITE) == "1.5"
    with pytest.raises(KorbaseError):
        render_literal("a\x00b", SQLITE)


