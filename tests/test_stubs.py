"""Tests for the typed columns generator."""

from __future__ import annotations

import importlib
import sys
from pathlib import Path

import pytest

import korbase
from korbase import KorbaseError
from korbase.stubs import generate, main

MODELS = """
import datetime
import uuid
from dataclasses import dataclass
from decimal import Decimal
from typing import Annotated, Optional, TypedDict

import msgspec

from korbase import PK, Rel, table


class Money:
    pass


@table("authors")
class Author(msgspec.Struct):
    id: Annotated[int, PK()]
    name: str


@table("posts")
@dataclass
class Post:
    id: Annotated[int, PK()]
    title: str
    author_id: int
    price: Decimal
    uid: uuid.UUID
    born: Optional[datetime.datetime]
    tags: list[str]
    cost: Money
    author: Annotated[Author, Rel("author_id")]


@table("notes")
class Note(TypedDict):
    id: Annotated[int, PK()]
    body: "str | None"
"""


@pytest.fixture
def models(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> str:
    """Write a models module to a temp dir and return its import name."""
    name = f"stub_models_{abs(hash(str(tmp_path)))}"
    (tmp_path / f"{name}.py").write_text(MODELS)
    monkeypatch.syspath_prepend(str(tmp_path))
    yield name
    sys.modules.pop(name, None)


def _load(source: str, tmp_path: Path, name: str):
    """Write the generated source, compile and import it."""
    path = tmp_path / f"{name}_cols.py"
    path.write_text(source)
    compile(source, str(path), "exec")
    return importlib.import_module(path.stem)


def test_generate_and_import(models: str, tmp_path: Path) -> None:
    """The output imports, and `cols` is the same cached object as korbase's."""
    out = generate(models)
    assert out.startswith("# generated by korbase.stubs, do not edit; rerun after changing models")
    mod = _load(out, tmp_path, models)
    post = importlib.import_module(models).Post
    assert mod.cols(post) is korbase.cols(post)
    assert generate(models) == out


def test_types_rendered(models: str) -> None:
    """Each field gets its Python type; unknown types fall back to Any."""
    out = generate(models)
    assert "    title: Column[str]" in out
    assert "    price: Column[decimal.Decimal]" in out
    assert "    uid: Column[uuid.UUID]" in out
    assert "    born: Column[datetime.datetime | None]" in out
    assert "    tags: Column[list[str]]" in out
    assert "    cost: Column[Any]" in out
    assert "    author: RelRef[Author]" in out
    assert "    body: Column[str | None]" in out
    assert "def cols(model: type[Post]) -> PostColumns: ..." in out


def test_check_and_write(models: str, tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    """`-o` writes the file; `--check` passes when current and fails when stale."""
    target = tmp_path / "out" / "cols.py"
    target.parent.mkdir()
    assert main([models, "-o", str(target), "--check"]) == 1
    assert main([models, "-o", str(target)]) == 0
    assert target.read_text() == generate(models)
    assert not list(target.parent.glob(".korbase-*"))
    assert main([models, "-o", str(target), "--check"]) == 0
    target.write_text("# old\n")
    capsys.readouterr()
    assert main([models, "-o", str(target), "--check"]) == 1
    assert "out of date" in capsys.readouterr().err


def test_errors_are_one_line(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    """A missing module is a one-line error, not a traceback."""
    assert main(["no_such_models_module", "-o", str(tmp_path / "x.py")]) == 1
    err = capsys.readouterr().err
    assert err.startswith("error:") and "Traceback" not in err


def test_name_collision(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """Two models with the same name from different modules are rejected."""
    body = 'from typing import Annotated\nfrom dataclasses import dataclass\nfrom korbase import PK, table\n\n@table("{t}")\n@dataclass\nclass Post:\n    id: Annotated[int, PK()]\n'
    (tmp_path / "stub_a.py").write_text(body.format(t="a"))
    (tmp_path / "stub_b.py").write_text(body.format(t="b"))
    (tmp_path / "stub_both.py").write_text("from stub_a import Post\nfrom stub_b import Post as Post2\n")
    monkeypatch.syspath_prepend(str(tmp_path))
    with pytest.raises(KorbaseError, match="two models are named"):
        generate("stub_both")


def test_committed_typecheck_module_is_current(monkeypatch: pytest.MonkeyPatch) -> None:
    """tests/typecheck/gen_models_cols.py matches what the generator writes."""
    folder = Path(__file__).parent / "typecheck"
    monkeypatch.syspath_prepend(str(folder))
    expected = generate("gen_models")
    assert (folder / "gen_models_cols.py").read_text() == expected
