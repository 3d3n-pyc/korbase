"""Turn models into `CREATE TABLE` statements."""

from __future__ import annotations

import datetime
import enum
import math
import typing
import uuid
from decimal import Decimal
from typing import Any

from korbase._backend import Conn
from korbase._dialect import PG, Dialect
from korbase._ident import KorbaseError, quote_ident
from korbase._meta import ColumnMeta, Default, TableMeta, constraint_name, table_meta

__all__ = ["sql_type", "render_literal", "create_table_sql", "create_all_sql", "create_all"]

_TYPES: dict[Any, str] = {
    bool: "boolean",
    int: "bigint",
    float: "double precision",
    str: "text",
    bytes: "bytea",
    uuid.UUID: "uuid",
    datetime.datetime: "timestamptz",
    datetime.date: "date",
    datetime.time: "time",
    Decimal: "numeric",
    dict: "jsonb",
    list: "jsonb",
}


def sql_type(col: ColumnMeta) -> str:
    """Return the Postgres type of a column: its `SqlType`, or the mapped Python type.

    Raises `KorbaseError` for a Python type with no mapping; give it a `SqlType`.
    """
    if col.sql_type is not None:
        return col.sql_type
    tp = col.python_type
    found = _TYPES.get(typing.get_origin(tp) or tp)
    if found is None and isinstance(tp, type) and issubclass(tp, enum.Enum):
        found = "text"
    if found is None:
        raise KorbaseError(f"column {col.name!r}: no SQL type for {tp!r}; add SqlType(...)")
    return found


def render_literal(value: Any, dialect: Dialect = PG) -> str:
    """Return `value` as a SQL literal for a column default.

    Handles None, bool, finite numbers and str. On Postgres, strings double
    their single quotes and backslashes in an escape string (`E'...'`), which
    is safe whatever `standard_conforming_strings` is, and bools are
    `TRUE`/`FALSE`. On SQLite, bools are `1`/`0` and strings only double their
    single quotes. A NUL character is refused.
    """
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        if dialect.name == "sqlite":
            return "1" if value else "0"
        return "TRUE" if value else "FALSE"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float) and math.isfinite(value):
        return repr(value)
    if isinstance(value, str):
        if "\x00" in value:
            raise KorbaseError("a default string cannot contain a NUL character")
        if dialect.name == "sqlite":
            return "'" + value.replace("'", "''") + "'"
        return "E'" + value.replace("\\", "\\\\").replace("'", "''") + "'"
    raise KorbaseError(f"unsupported default value: {value!r}")


def _default_sql(default: Default, dialect: Dialect) -> str:
    """Return the SQL of a `Default`: the raw expression, or the rendered literal."""
    return default.sql if default.sql is not None else render_literal(default.value, dialect)


def _is_rowid_pk(meta: TableMeta, col: ColumnMeta, dialect: Dialect) -> bool:
    """Return true when `col` is the single auto-numbered key of a SQLite table."""
    return dialect.integer_pk_identity and col.identity and meta.pk == (col.name,)


def _type_sql(col: ColumnMeta, dialect: Dialect) -> str:
    """Return the column type for the dialect; a `SqlType` is used as written."""
    if dialect.name != "sqlite":
        return sql_type(col)
    return col.sql_type or dialect.sql_type(col.python_type)


def _column_sql(meta: TableMeta, col: ColumnMeta, dialect: Dialect) -> str:
    """Return one column definition."""
    if _is_rowid_pk(meta, col, dialect):
        parts = [quote_ident(col.name), "INTEGER PRIMARY KEY"]
    else:
        parts = [quote_ident(col.name), _type_sql(col, dialect)]
        if col.identity and dialect.name != "sqlite":
            parts.append("GENERATED BY DEFAULT AS IDENTITY")
        if not col.nullable or col.pk:
            parts.append("NOT NULL")
    if col.default is not None:
        parts.append("DEFAULT " + _default_sql(col.default, dialect))
    return " ".join(parts)


def _cols(names: typing.Iterable[str]) -> str:
    """Return a quoted, comma-separated column list."""
    return ", ".join(quote_ident(n) for n in names)


def _fk_def(meta: TableMeta, col: ColumnMeta) -> str:
    """Return the `CONSTRAINT ... FOREIGN KEY ...` clause of one foreign key."""
    assert col.fk is not None
    target, target_col = col.fk.target.split(".")
    name = constraint_name(meta.name, "fkey", (col.name,))
    return (
        f"CONSTRAINT {quote_ident(name)} FOREIGN KEY ({quote_ident(col.name)}) "
        f"REFERENCES {quote_ident(target)} ({quote_ident(target_col)}) "
        f"ON DELETE {col.fk.on_delete.upper()}"
    )


def _fk_sql(meta: TableMeta, col: ColumnMeta) -> str:
    """Return the `ALTER TABLE` that adds one foreign key (Postgres)."""
    return f"ALTER TABLE {quote_ident(meta.name)} ADD {_fk_def(meta, col)}"


def _index_sql(meta: TableMeta) -> list[str]:
    """Return the `CREATE INDEX` statements of a table."""
    out = []
    for idx in meta.indexes:
        name = idx.name or constraint_name(meta.name, "idx", idx.columns)
        unique = "UNIQUE " if idx.unique else ""
        where = f" WHERE {idx.where}" if idx.where else ""
        target = f"{quote_ident(name)} ON {quote_ident(meta.name)} ({_cols(idx.columns)})"
        out.append(f"CREATE {unique}INDEX {target}{where}")
    return out


def _create_sql(meta: TableMeta, dialect: Dialect = PG) -> str:
    """Return the `CREATE TABLE` statement: primary key, uniques, and on SQLite the foreign keys."""
    lines = [_column_sql(meta, c, dialect) for c in meta.columns]
    if not any(_is_rowid_pk(meta, c, dialect) for c in meta.columns):
        lines.append(f"CONSTRAINT {quote_ident(constraint_name(meta.name, 'pkey'))} PRIMARY KEY ({_cols(meta.pk)})")
    for col in meta.columns:
        if col.unique:
            name = constraint_name(meta.name, "key", (col.name,))
            lines.append(f"CONSTRAINT {quote_ident(name)} UNIQUE ({quote_ident(col.name)})")
    if dialect.name == "sqlite":
        lines.extend(_fk_def(meta, c) for c in meta.columns if c.fk is not None)
    return f"CREATE TABLE {quote_ident(meta.name)} (\n    " + ",\n    ".join(lines) + "\n)"


def _fks(meta: TableMeta, dialect: Dialect) -> list[str]:
    """Return the separate foreign key statements (none on SQLite, where they are inline)."""
    if dialect.name == "sqlite":
        return []
    return [_fk_sql(meta, c) for c in meta.columns if c.fk is not None]


def create_table_sql(meta: TableMeta, dialect: Dialect = PG) -> list[str]:
    """Return the statements that create one table: the table, its foreign keys, its indexes.

    On SQLite the foreign keys are inside `CREATE TABLE`.
    """
    return [_create_sql(meta, dialect), *_fks(meta, dialect), *_index_sql(meta)]


def create_all_sql(models: typing.Iterable[type], dialect: Dialect = PG) -> list[str]:
    """Return the statements that create every model: tables, then foreign keys, then indexes.

    Models are ordered by table name, so the output is the same on every run.
    """
    metas = sorted((table_meta(m) for m in models), key=lambda m: m.name)
    tables = [_create_sql(m, dialect) for m in metas]
    fks = [s for m in metas for s in _fks(m, dialect)]
    return [*tables, *fks, *[s for m in metas for s in _index_sql(m)]]


async def create_all(
    conn: Conn, models: typing.Iterable[type], schema: str | None = None, dialect: Dialect = PG
) -> None:
    """Create the tables of `models` on `conn`.

    On Postgres, with `schema`, the tables are created there (`SET LOCAL
    search_path`); that needs a transaction, which the caller opens and ends.
    On SQLite there are no schemas (`schema` must be None) and the statements
    run in one transaction opened here.
    """
    statements = create_all_sql(models, dialect)
    if dialect.name == "sqlite":
        if schema is not None:
            raise KorbaseError("SQLite has no schemas: schema must be None")
        async with conn.transaction():
            await conn.execute_script(";\n".join(statements))
        return
    if schema is not None:
        statements.insert(0, f"SET LOCAL search_path TO {quote_ident(schema)}, public")
    await conn.execute_script(";\n".join(statements))
