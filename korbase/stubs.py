"""Generate typed column views of your models, for type checkers.

Run `python -m korbase.stubs app.models -o app/columns.py`. The generated
module holds one `<Model>Columns` class per model and a typed `cols`
function. Import `cols` from it instead of `korbase`: `cols(Post).title` is
then a `Column[str]`, and a typo is an error in your editor. At runtime it is
the same object as `korbase.cols(Post)`.

`--check` writes nothing and exits 1 if the file is out of date, for CI.
"""

from __future__ import annotations

import argparse
import importlib
import keyword
import os
import sys
import tempfile
import types
import typing
from collections.abc import Sequence
from pathlib import Path
from typing import Any, Optional, Union

from korbase._ident import KorbaseError
from korbase._meta import _ATTR, TableMeta, table_meta

__all__ = ["generate", "main"]

_HEADER = "# generated by korbase.stubs, do not edit; rerun after changing models"
_BUILTINS = ("int", "str", "float", "bool", "bytes", "list", "dict", "set", "frozenset", "tuple")
_MODULES = ("datetime", "uuid", "decimal")
_RESERVED = ("Any", "Column", "RelRef", "overload", "cols", "_cols")


def _render(tp: Any, imports: set[str]) -> str:
    """Return the annotation text for `tp`, or `Any` if it cannot be shown."""
    origin = typing.get_origin(tp)
    if tp is Any or tp is Ellipsis:
        return "..." if tp is Ellipsis else "Any"
    if tp is None or tp is type(None):
        return "None"
    if origin is typing.Annotated:
        return _render(typing.get_args(tp)[0], imports)
    if origin in (Union, types.UnionType):
        return " | ".join(_render(a, imports) for a in typing.get_args(tp))
    if origin is not None:
        return _render_generic(origin, typing.get_args(tp), imports)
    return _render_class(tp, imports)


def _render_generic(origin: Any, args: tuple[Any, ...], imports: set[str]) -> str:
    """Return `list[int]`-style text for a builtin generic, else `Any`."""
    if origin not in (list, dict, set, frozenset, tuple) or not args:
        return "Any"
    return f"{origin.__name__}[{', '.join(_render(a, imports) for a in args)}]"


def _render_class(tp: Any, imports: set[str]) -> str:
    """Return the text for a plain class: a builtin or a stdlib date, uuid or decimal type."""
    if not isinstance(tp, type):
        return "Any"
    if tp.__module__ == "builtins" and tp.__name__ in _BUILTINS:
        return tp.__name__
    if tp.__module__ in _MODULES and "." not in tp.__qualname__:
        imports.add(tp.__module__)
        return f"{tp.__module__}.{tp.__qualname__}"
    return "Any"


def _column_type(col: Any, imports: set[str]) -> str:
    """Return the `Column[...]` type of one column."""
    text = _render(col.python_type, imports)
    if col.nullable and text != "Any":
        text += " | None"
    return f"Column[{text}]"


def _models(module_path: str) -> dict[str, type]:
    """Return the `@table` classes of the module by the name the module gives them."""
    module = importlib.import_module(module_path)
    found = {k: v for k, v in vars(module).items() if isinstance(v, type) and _ATTR in v.__dict__}
    if not found:
        raise KorbaseError(f"no models found in {module_path}")
    return _check_names(found)


def _check_names(found: dict[str, type]) -> dict[str, type]:
    """Raise `KorbaseError` if a model name is unusable or two models share a name."""
    seen: dict[str, type] = {}
    for key, model in found.items():
        if not key.isidentifier() or keyword.iskeyword(key) or key in _RESERVED:
            raise KorbaseError(f"model name {key!r} cannot be used in a generated module")
        if seen.setdefault(model.__name__, model) is not model:
            raise KorbaseError(f"two models are named {model.__name__!r}; rename one")
    return found


def _class_lines(name: str, meta: TableMeta, names: dict[type, str], imports: set[str]) -> list[str]:
    """Return the source lines of the `<Model>Columns` class."""
    lines = [f"class {name}Columns:", f'    """Typed columns of `{name}`."""', ""]
    for col in meta.columns:
        lines.append(f"    {col.name}: {_column_type(col, imports)}")
    for rel in meta.relations:
        target = names.get(rel.target_model, "Any")
        lines.append(f"    {rel.name}: RelRef[{target}]")
    return lines


def generate(models_module: str) -> str:
    """Return the source of the typed columns module for `models_module`.

    Raises `KorbaseError` if the module has no models or two share a name.
    """
    found = _models(models_module)
    names = {model: key for key, model in found.items()}
    imports: set[str] = set()
    body: list[str] = []
    for key, model in found.items():
        body += ["", ""] + _class_lines(key, table_meta(model), names, imports)
    for key in found:
        body += ["", "", "@overload", f"def cols(model: type[{key}]) -> {key}Columns: ..."]
    body += [
        "",
        "",
        "def cols(model: Any) -> Any:",
        '    """Return the columns of `model`."""',
        "    return _cols(model)",
        "",
    ]
    return "\n".join(_head(models_module, found, imports) + body)


def _head(models_module: str, found: dict[str, type], imports: set[str]) -> list[str]:
    """Return the header comment and import lines."""
    lines = [_HEADER, "# ruff: noqa", "", "from __future__ import annotations", ""]
    lines += [f"import {m}" for m in sorted(imports)]
    lines += [
        "from typing import Any, overload",
        "",
        "from korbase import Column, RelRef",
        "from korbase import cols as _cols",
    ]
    lines += [f"from {models_module} import {', '.join(found)}"]
    return lines


def _write_atomic(path: Path, text: str) -> None:
    """Write `text` to `path` through a temporary file and a rename."""
    fd, tmp = tempfile.mkstemp(dir=path.resolve().parent, prefix=".korbase-", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def _parser() -> argparse.ArgumentParser:
    """Build the command-line parser."""
    p = argparse.ArgumentParser(prog="python -m korbase.stubs", description=__doc__)
    p.add_argument("models", help="dotted path of the module holding the models")
    p.add_argument("-o", "--output", required=True, help="file to write")
    p.add_argument("--check", action="store_true", help="exit 1 if the file is out of date; write nothing")
    return p


def _run(args: argparse.Namespace) -> int:
    """Write or check the output file; return the exit code."""
    path = Path(args.output)
    text = generate(args.models)
    if args.check:
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != text:
            print(f"error: {path} is out of date; rerun python -m korbase.stubs", file=sys.stderr)
            return 1
        return 0
    _write_atomic(path, text)
    return 0


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Run the command line; return the exit code (0 on success, 1 on error)."""
    args = _parser().parse_args(argv)
    sys.path.insert(0, os.getcwd())
    try:
        return _run(args)
    except Exception as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
