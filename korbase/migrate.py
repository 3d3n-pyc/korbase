"""Generate, apply and list SQL migrations.

`make` compares your models with the database and writes the SQL file that
closes the gap; `apply` runs the reviewed files; `status` lists them. From a
shell: `python -m korbase.migrate make --models app.models --dir migrations`.
The DSN comes from `--dsn`, or else the `KORBASE_DSN` environment variable;
`--dsn` wins. Prefer the variable: a command-line argument shows up in `ps`.
"""

from __future__ import annotations

import argparse
import asyncio
import contextlib
import datetime
import importlib
import os
import re
import secrets
import sys
from collections.abc import Iterable, Sequence
from pathlib import Path
from typing import Optional

from korbase import _ddl
from korbase._db import Database
from korbase._diff import diff, render
from korbase._ident import KorbaseError, quote_ident
from korbase._inspect import inspect
from korbase._runner import apply, status

__all__ = ["apply", "status", "create_all", "make", "collect_models", "main"]

_NUMBER = re.compile(r"(\d{4,})_")
_ATTR = "__korbase_table__"


class _Rollback(Exception):
    """Raised on purpose to end a transaction with a rollback."""


async def create_all(db: Database, models: Iterable[type]) -> None:
    """Create the tables of `models` in one transaction; handy in tests."""
    async with db._conn() as conn, conn.transaction():
        await _ddl.create_all(conn, models)


def _slug(message: str) -> str:
    """Turn a message into a file-name part: `[a-z0-9_]`, at most 40 characters."""
    slug = re.sub(r"[^a-z0-9]+", "_", message.lower()).strip("_")[:40].strip("_")
    return slug or "migration"


def _next_number(directory: Path) -> int:
    """Return the number after the highest `NNNN_*.sql` file in `directory`."""
    found = [int(m.group(1)) for p in directory.glob("*.sql") if (m := _NUMBER.match(p.name))]
    return max(found, default=0) + 1


def _write_new(directory: Path, message: str, sql: str) -> Path:
    """Write `sql` to the next numbered file, never replacing an existing one."""
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"{_next_number(directory):04d}_{_slug(message)}.sql"
    header = f"-- Generated by korbase on {datetime.date.today().isoformat()}.\n"
    with path.open("x", encoding="utf-8") as f:
        f.write(header + sql)
    return path


async def _changes(db: Database, models: Iterable[type]) -> str:
    """Return the SQL moving `public` to the models, using a scratch schema that is rolled back."""
    scratch = f"korbase_scratch_{os.getpid()}_{secrets.token_hex(4)}"
    sql = ""
    with contextlib.suppress(_Rollback):
        async with db._conn() as conn, conn.transaction():
            await conn.execute_script(f"CREATE SCHEMA {quote_ident(scratch)}")
            await _ddl.create_all(conn, models, schema=scratch)
            desired = await inspect(conn, scratch)
            current = await inspect(conn, "public")
            sql = render(diff(current, desired))
            raise _Rollback
    return sql


async def make(db: Database, models: Iterable[type], directory: str | os.PathLike[str], message: str) -> Optional[Path]:
    """Write the next migration file for the difference between `models` and `public`.

    Returns the new file's path, or None when nothing differs. The database is
    left untouched: the comparison runs in a transaction that is rolled back.
    """
    models = list(models)
    if not models:
        raise KorbaseError("no models given")
    sql = await _changes(db, models)
    if not sql:
        return None
    return _write_new(Path(directory), message, sql)


def collect_models(module_path: str) -> list[type]:
    """Import the module `module_path` and return its `@table` classes.

    Classes defined in it or imported into it count; each appears once.
    Raises KorbaseError when the module holds none.
    """
    module = importlib.import_module(module_path)
    found = [v for v in vars(module).values() if isinstance(v, type) and _ATTR in v.__dict__]
    if not found:
        raise KorbaseError(f"no models found in {module_path}")
    return list(dict.fromkeys(found))


def _parser() -> argparse.ArgumentParser:
    """Build the command-line parser."""
    p = argparse.ArgumentParser(prog="python -m korbase.migrate", description=__doc__)
    p.add_argument("command", choices=["make", "apply", "status"])
    p.add_argument("--models", help="dotted path of the module holding the models")
    p.add_argument("--dir", default="migrations", help="migrations directory")
    p.add_argument("-m", "--message", default="migration", help="name for the new file")
    p.add_argument("--dsn", help="database DSN; wins over $KORBASE_DSN (visible in `ps`: prefer the variable)")
    return p


async def _run(args: argparse.Namespace, dsn: str) -> None:
    """Run the chosen command against the database at `dsn`."""
    try:
        db = await Database.connect(dsn)
    except Exception:
        raise KorbaseError("could not connect to the database") from None
    async with db:
        if args.command == "make":
            path = await make(db, collect_models(args.models), args.dir, args.message)
            print(path if path else "no changes")
        elif args.command == "apply":
            for name in await apply(db, args.dir):
                print(f"applied {name}")
        else:
            for name, state in await status(db, args.dir):
                print(f"{state} {name}")


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Run the command line; return the exit code (0 on success, 1 on error)."""
    args = _parser().parse_args(argv)
    dsn = args.dsn or os.environ.get("KORBASE_DSN")
    if not dsn:
        print("error: set KORBASE_DSN or pass --dsn", file=sys.stderr)
        return 1
    if args.command == "make" and not args.models:
        print("error: make needs --models", file=sys.stderr)
        return 1
    try:
        asyncio.run(_run(args, dsn))
    except Exception as exc:
        print(f"error: {str(exc).replace(dsn, '***')}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
