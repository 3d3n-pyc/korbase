"""Compare two schema snapshots and render the SQL that turns one into the other."""

from __future__ import annotations

from dataclasses import dataclass

from korbase._ddl import _cols
from korbase._ident import quote_ident
from korbase._schema import Column, ForeignKey, Index, Snapshot, Table

__all__ = ["Change", "diff", "render"]

CREATE_TABLE, ADD_COLUMN, ALTER_COLUMN, DROP_CHANGED, ADD_KEY, ADD_FK, ADD_INDEX = 10, 20, 30, 40, 50, 60, 70
DROP_FK, DROP_OTHER, DROP_COLUMN, DROP_TABLE = 80, 85, 90, 95


@dataclass(frozen=True)
class Change:
    """One SQL statement, its comment lines, and its place in the order."""

    phase: int
    sql: str
    comments: tuple[str, ...] = ()


def _review(reason: str) -> str:
    """Return the review marker line for a dangerous change."""
    return f"-- korbase:review {reason}"


def _column_def(col: Column) -> str:
    """Return the definition of a column, as in `CREATE TABLE`."""
    parts = [quote_ident(col.name), col.type]
    if col.identity:
        parts.append("GENERATED BY DEFAULT AS IDENTITY")
    if not col.nullable:
        parts.append("NOT NULL")
    if col.default is not None:
        parts.append("DEFAULT " + col.default)
    return " ".join(parts)


def _alter(table: str, action: str) -> str:
    """Return an `ALTER TABLE` statement."""
    return f"ALTER TABLE {quote_ident(table)} {action}"


def _pk_sql(table: Table) -> str:
    """Return the statement that adds the primary key of `table`."""
    assert table.pk is not None
    name = table.pk_name or f"{table.name}_pkey"
    return _alter(table.name, f"ADD CONSTRAINT {quote_ident(name)} PRIMARY KEY ({_cols(table.pk)})")


def _unique_sql(table: str, name: str, columns: tuple[str, ...]) -> str:
    """Return the statement that adds a unique constraint."""
    return _alter(table, f"ADD CONSTRAINT {quote_ident(name)} UNIQUE ({_cols(columns)})")


def _fk_sql(table: str, fk: ForeignKey) -> str:
    """Return the statement that adds a foreign key."""
    return _alter(
        table,
        f"ADD CONSTRAINT {quote_ident(fk.name)} FOREIGN KEY ({_cols(fk.columns)}) "
        f"REFERENCES {quote_ident(fk.target_table)} ({_cols(fk.target_columns)}) "
        f"ON DELETE {fk.on_delete.upper()}",
    )


def _index_sql(table: str, idx: Index) -> str:
    """Return the statement that creates an index."""
    unique = "UNIQUE " if idx.unique else ""
    return f"CREATE {unique}INDEX {quote_ident(idx.name)} ON {quote_ident(table)} ({_cols(idx.columns)})"


def _drop_constraint(table: str, name: str) -> str:
    """Return the statement that drops a constraint."""
    return _alter(table, f"DROP CONSTRAINT {quote_ident(name)}")


def _create_table(table: Table) -> list[Change]:
    """Return the changes that create a whole table (foreign keys and indexes come later)."""
    lines = [_column_def(c) for c in table.columns]
    if table.pk is not None:
        name = table.pk_name or f"{table.name}_pkey"
        lines.append(f"CONSTRAINT {quote_ident(name)} PRIMARY KEY ({_cols(table.pk)})")
    for name, cols in table.uniques:
        lines.append(f"CONSTRAINT {quote_ident(name)} UNIQUE ({_cols(cols)})")
    sql = f"CREATE TABLE {quote_ident(table.name)} (\n    " + ",\n    ".join(lines) + "\n)"
    out = [Change(CREATE_TABLE, sql)]
    out += [Change(ADD_FK, _fk_sql(table.name, fk)) for fk in table.foreign_keys]
    out += [Change(ADD_INDEX, _index_sql(table.name, i)) for i in table.indexes]
    return out


def _drop_table(table: Table) -> list[Change]:
    """Return the changes that drop a table, foreign keys first."""
    out = [Change(DROP_FK, _drop_constraint(table.name, fk.name)) for fk in table.foreign_keys]
    reason = _review(f"drops table {table.name}, its data is lost")
    return [*out, Change(DROP_TABLE, f"DROP TABLE {quote_ident(table.name)}", (reason,))]


def _alter_column(table: str, old: Column, new: Column) -> list[Change]:
    """Return the changes that turn column `old` into `new`."""
    col, out = quote_ident(new.name), []

    def add(sql: str, *comments: str) -> None:
        """Append one column change."""
        out.append(Change(ALTER_COLUMN, _alter(table, f"ALTER COLUMN {col} {sql}"), comments))

    if old.type != new.type:
        why = _review(f"type of {table}.{new.name} changes from {old.type} to {new.type}")
        add(f"TYPE {new.type} USING {col}::{new.type}", why)
    if old.nullable != new.nullable:
        if new.nullable:
            add("DROP NOT NULL")
        else:
            add("SET NOT NULL", _review(f"{table}.{new.name} becomes NOT NULL, fails if NULLs exist"))
    if old.default != new.default:
        add("DROP DEFAULT" if new.default is None else f"SET DEFAULT {new.default}")
    if old.identity != new.identity:
        why = _review(f"identity of {table}.{new.name} changes")
        add("ADD GENERATED BY DEFAULT AS IDENTITY" if new.identity else "DROP IDENTITY", why)
    return out


def _diff_columns(cur: Table, des: Table) -> list[Change]:
    """Return the column changes of a table present on both sides."""
    t = cur.name
    old = {c.name: c for c in cur.columns}
    new = {c.name: c for c in des.columns}
    dropped = [c for c in cur.columns if c.name not in new]
    added = [c for c in des.columns if c.name not in old]
    hints = {}
    for gone, came in zip(dropped, added, strict=False):
        hints[gone.name] = hints[came.name] = (
            f"-- possible rename: rewrite as ALTER TABLE {quote_ident(t)} "
            f"RENAME COLUMN {quote_ident(gone.name)} TO {quote_ident(came.name)}"
        )
    out = []
    for c in added:
        out.append(Change(ADD_COLUMN, _alter(t, f"ADD COLUMN {_column_def(c)}"), _hint(hints, c.name)))
    for c in des.columns:
        if c.name in old:
            out += _alter_column(t, old[c.name], c)
    for c in dropped:
        why = _review(f"drops column {t}.{c.name}, its data is lost")
        sql = _alter(t, f"DROP COLUMN {quote_ident(c.name)}")
        out.append(Change(DROP_COLUMN, sql, (why, *_hint(hints, c.name))))
    return out


def _hint(hints: dict[str, str], name: str) -> tuple[str, ...]:
    """Return the rename hint of a column, if it has one."""
    return (hints[name],) if name in hints else ()


def _diff_keyed(cur: dict, des: dict, drop, add, kind: int) -> list[Change]:
    """Diff named items: `drop(name)` and `add(item)` give the SQL; `kind` is the add phase."""
    out = []
    for name, item in cur.items():
        if name not in des:
            out.append(Change(DROP_FK if kind == ADD_FK else DROP_OTHER, drop(name)))
        elif des[name] != item:
            out.append(Change(DROP_CHANGED, drop(name)))
    for name, item in des.items():
        if cur.get(name) != item:
            out.append(Change(kind, add(item)))
    return out


def _diff_pk(cur: Table, des: Table) -> list[Change]:
    """Return the primary key changes of a table."""
    if cur.pk == des.pk:
        return []
    out = []
    if cur.pk is not None:
        name = cur.pk_name or f"{cur.name}_pkey"
        late = des.pk is None
        why = () if late else (_review(f"primary key of {cur.name} changes"),)
        out.append(Change(DROP_OTHER if late else DROP_CHANGED, _drop_constraint(cur.name, name), why))
    if des.pk is not None:
        out.append(Change(ADD_KEY, _pk_sql(des)))
    return out


def _diff_keys(cur: Table, des: Table) -> list[Change]:
    """Return the key, unique and index changes of a table present on both sides."""
    t = cur.name
    out = _diff_pk(cur, des)
    out += _diff_uniques(cur, des)
    out += _diff_keyed(
        {f.name: f for f in cur.foreign_keys},
        {f.name: f for f in des.foreign_keys},
        lambda n: _drop_constraint(t, n),
        lambda f: _fk_sql(t, f),
        ADD_FK,
    )
    out += _diff_keyed(
        {i.name: i for i in cur.indexes},
        {i.name: i for i in des.indexes},
        lambda n: f"DROP INDEX {quote_ident(n)}",
        lambda i: _index_sql(t, i),
        ADD_INDEX,
    )
    return out


def _diff_uniques(cur: Table, des: Table) -> list[Change]:
    """Return the unique constraint changes of a table."""
    t = cur.name
    old, new = dict(cur.uniques), dict(des.uniques)
    out = []
    for name, cols in old.items():
        if name not in new:
            out.append(Change(DROP_OTHER, _drop_constraint(t, name)))
        elif new[name] != cols:
            out.append(Change(DROP_CHANGED, _drop_constraint(t, name)))
    for name, cols in new.items():
        if old.get(name) != cols:
            out.append(Change(ADD_KEY, _unique_sql(t, name, cols)))
    return out


def diff(current: Snapshot, desired: Snapshot) -> list[Change]:
    """Return the changes that turn `current` into `desired`, in a safe order."""
    out: list[Change] = []
    for name in sorted(set(current.tables) | set(desired.tables)):
        cur, des = current.tables.get(name), desired.tables.get(name)
        if cur is None and des is not None:
            out += _create_table(des)
        elif des is None and cur is not None:
            out += _drop_table(cur)
        elif cur is not None and des is not None:
            out += _diff_columns(cur, des) + _diff_keys(cur, des)
    return sorted(out, key=lambda c: c.phase)


def render(changes: list[Change]) -> str:
    """Return the SQL file body for `changes`: comment lines, then each statement ending in `;`."""
    return "".join("".join(f"{c}\n" for c in ch.comments) + ch.sql + ";\n" for ch in changes)
