"""Compare two schema snapshots and render the SQL that turns one into the other."""

from __future__ import annotations

from dataclasses import dataclass, replace

from korbase._ddl import _cols
from korbase._dialect import PG, Dialect
from korbase._dialect import SQLITE as LITE
from korbase._ident import quote_ident
from korbase._schema import Column, ForeignKey, Index, Snapshot, Table, normalize_where

__all__ = ["Change", "diff", "render"]

CREATE_TABLE, ADD_COLUMN, ALTER_COLUMN, DROP_CHANGED, ADD_KEY, ADD_FK, ADD_INDEX = 10, 20, 30, 40, 50, 60, 70
DROP_FK, DROP_OTHER, DROP_COLUMN, DROP_TABLE = 80, 85, 90, 95
DROP_DEPENDENT_FK = 35


@dataclass(frozen=True)
class Change:
    """One SQL statement, its comment lines, and its place in the order."""

    phase: int
    sql: str
    comments: tuple[str, ...] = ()
    rebuild: bool = False


def _review(reason: str) -> str:
    """Return the review marker line for a dangerous change."""
    return f"-- korbase:review {reason}"


def _column_def(col: Column, dialect: Dialect = PG, rowid: bool = False) -> str:
    """Return the definition of a column, as in `CREATE TABLE`; `rowid` marks a SQLite `INTEGER PRIMARY KEY`."""
    parts = [quote_ident(col.name), "INTEGER PRIMARY KEY" if rowid else col.type]
    if col.identity and not rowid and dialect.name != "sqlite":
        parts.append("GENERATED BY DEFAULT AS IDENTITY")
    if not col.nullable and not rowid:
        parts.append("NOT NULL")
    if col.default is not None:
        parts.append("DEFAULT " + col.default)
    return " ".join(parts)


def _alter(table: str, action: str) -> str:
    """Return an `ALTER TABLE` statement."""
    return f"ALTER TABLE {quote_ident(table)} {action}"


def _pk_sql(table: Table) -> str:
    """Return the statement that adds the primary key of `table`."""
    assert table.pk is not None
    name = table.pk_name or f"{table.name}_pkey"
    return _alter(table.name, f"ADD CONSTRAINT {quote_ident(name)} PRIMARY KEY ({_cols(table.pk)})")


def _unique_sql(table: str, name: str, columns: tuple[str, ...]) -> str:
    """Return the statement that adds a unique constraint."""
    return _alter(table, f"ADD CONSTRAINT {quote_ident(name)} UNIQUE ({_cols(columns)})")


def _fk_sql(table: str, fk: ForeignKey) -> str:
    """Return the statement that adds a foreign key."""
    return _alter(
        table,
        f"ADD CONSTRAINT {quote_ident(fk.name)} FOREIGN KEY ({_cols(fk.columns)}) "
        f"REFERENCES {quote_ident(fk.target_table)} ({_cols(fk.target_columns)}) "
        f"ON DELETE {fk.on_delete.upper()}",
    )


def _index_sql(table: str, idx: Index) -> str:
    """Return the statement that creates an index."""
    unique = "UNIQUE " if idx.unique else ""
    where = f" WHERE {idx.where}" if idx.where else ""
    return f"CREATE {unique}INDEX {quote_ident(idx.name)} ON {quote_ident(table)} ({_cols(idx.columns)}){where}"


def _norm_index(idx: Index) -> Index:
    """Return the index with its predicate normalised, so equal predicates compare equal."""
    return replace(idx, where=normalize_where(idx.where) if idx.where else None)


def _drop_constraint(table: str, name: str) -> str:
    """Return the statement that drops a constraint."""
    return _alter(table, f"DROP CONSTRAINT {quote_ident(name)}")


def _sqlite_fk_def(fk: ForeignKey) -> str:
    """Return the inline foreign key clause of a SQLite `CREATE TABLE`."""
    return (
        f"CONSTRAINT {quote_ident(fk.name)} FOREIGN KEY ({_cols(fk.columns)}) "
        f"REFERENCES {quote_ident(fk.target_table)} ({_cols(fk.target_columns)}) "
        f"ON DELETE {fk.on_delete.upper()}"
    )


def _create_table(table: Table, dialect: Dialect = PG) -> list[Change]:
    """Return the changes that create a whole table (foreign keys and indexes come later; inline on SQLite)."""
    lite = dialect.name == "sqlite"
    rowid = table.pk[0] if lite and table.pk is not None and len(table.pk) == 1 else None
    lines = [_column_def(c, dialect, c.identity and c.name == rowid) for c in table.columns]
    if table.pk is not None and not any(c.identity and c.name == rowid for c in table.columns):
        name = table.pk_name or f"{table.name}_pkey"
        lines.append(f"CONSTRAINT {quote_ident(name)} PRIMARY KEY ({_cols(table.pk)})")
    for name, cols in table.uniques:
        lines.append(f"CONSTRAINT {quote_ident(name)} UNIQUE ({_cols(cols)})")
    if lite:
        lines += [_sqlite_fk_def(fk) for fk in table.foreign_keys]
    sql = f"CREATE TABLE {quote_ident(table.name)} (\n    " + ",\n    ".join(lines) + "\n)"
    out = [Change(CREATE_TABLE, sql)]
    if not lite:
        out += [Change(ADD_FK, _fk_sql(table.name, fk)) for fk in table.foreign_keys]
    out += [Change(ADD_INDEX, _index_sql(table.name, i)) for i in table.indexes]
    return out


def _drop_table(table: Table, dialect: Dialect = PG) -> list[Change]:
    """Return the changes that drop a table, foreign keys first (Postgres)."""
    out = [Change(DROP_FK, _drop_constraint(table.name, fk.name)) for fk in table.foreign_keys]
    if dialect.name == "sqlite":
        out = []
    reason = _review(f"drops table {table.name}, its data is lost")
    return [*out, Change(DROP_TABLE, f"DROP TABLE {quote_ident(table.name)}", (reason,))]


def _alter_column(table: str, old: Column, new: Column) -> list[Change]:
    """Return the changes that turn column `old` into `new`."""
    col, out = quote_ident(new.name), []

    def add(sql: str, *comments: str) -> None:
        """Append one column change."""
        out.append(Change(ALTER_COLUMN, _alter(table, f"ALTER COLUMN {col} {sql}"), comments))

    reset = old.type != new.type and old.default is not None
    if reset:
        add("DROP DEFAULT")
    if old.type != new.type:
        why = _review(f"type of {table}.{new.name} changes from {old.type} to {new.type}")
        add(f"TYPE {new.type} USING {col}::{new.type}", why)
    if old.nullable != new.nullable:
        if new.nullable:
            add("DROP NOT NULL")
        else:
            add("SET NOT NULL", _review(f"{table}.{new.name} becomes NOT NULL, fails if NULLs exist"))
    if new.default is not None and (old.default != new.default or reset):
        add(f"SET DEFAULT {new.default}")
    elif new.default is None and old.default is not None and not reset:
        add("DROP DEFAULT")
    if old.identity != new.identity:
        why = _review(f"identity of {table}.{new.name} changes")
        add("ADD GENERATED BY DEFAULT AS IDENTITY" if new.identity else "DROP IDENTITY", why)
    return out


def _cast_type(old: Column, new: Column) -> bool:
    """Return true when the type of a column changes (SQLite compares types without case)."""
    return old.type.upper() != new.type.upper()


def _rebuild_needed(cur: Table, des: Table) -> bool:
    """Return true when SQLite cannot alter `cur` into `des` in place, so the table must be rebuilt."""
    old = {c.name: c for c in cur.columns}
    for c in des.columns:
        was = old.get(c.name)
        if was is None and not _add_in_place(des, c):
            return True
        if was is not None and (_cast_type(was, c) or was.nullable != c.nullable or was.default != c.default):
            return True
    shapes = lambda t: {_fk_shape(f) for f in t.foreign_keys}  # noqa: E731
    uniques = lambda t: {c for _, c in t.uniques}  # noqa: E731
    return cur.pk != des.pk or uniques(cur) != uniques(des) or shapes(cur) != shapes(des)


def _copy_reviews(cur: Table, des: Table) -> tuple[str, ...]:
    """Return the review lines for the data the copy into the rebuilt table can lose or fail on."""
    t, old, out = cur.name, {c.name: c for c in cur.columns}, []
    for c in des.columns:
        was = old.get(c.name)
        if was is None and not c.nullable and c.default is None and not c.identity:
            out.append(_review(f"new NOT NULL column {t}.{c.name} without default fails on a non-empty table"))
        elif was is not None and _cast_type(was, c):
            out.append(_review(f"type of {t}.{c.name} changes from {was.type} to {c.type}, copied with CAST"))
        elif was is not None and was.nullable and not c.nullable:
            out.append(_review(f"{t}.{c.name} becomes NOT NULL, fails if NULLs exist"))
    kept = {c.name for c in des.columns}
    out += [_review(f"drops column {t}.{c.name}, its data is lost") for c in cur.columns if c.name not in kept]
    return tuple(out)


def _copy_sql(cur: Table, des: Table, temp: str) -> str:
    """Return the `INSERT ... SELECT` that copies the shared columns of `cur` into `temp`."""
    old = {c.name: c for c in cur.columns}
    shared = [c for c in des.columns if c.name in old]
    picks = [
        f"CAST({quote_ident(c.name)} AS {c.type})" if _cast_type(old[c.name], c) else quote_ident(c.name)
        for c in shared
    ]
    names = ", ".join(quote_ident(c.name) for c in shared)
    return f"INSERT INTO {quote_ident(temp)} ({names}) SELECT {', '.join(picks)} FROM {quote_ident(cur.name)}"


def _lost_reviews(cur: Table, des: Table) -> tuple[str, ...]:
    """Return a review line per object the rebuild drops: unmanaged indexes, triggers, CHECK constraints."""
    t, kept = des.name, {i.name for i in des.indexes}
    out = [f'index "{i.name}"' for i in cur.indexes if i.name not in kept]
    out += [f'trigger "{n}"' for n in getattr(cur, "triggers", ())]
    if getattr(cur, "has_check", False):
        out.append("CHECK constraint")
    return tuple(_review(f'{what} on "{t}" is dropped by this rebuild; recreate it below') for what in out)


def _rebuild_table(cur: Table, des: Table) -> list[Change]:
    """Return the changes that rebuild a SQLite table: new table, copy, drop, rename, indexes."""
    temp = f"{des.name}__new"
    create = _create_table(replace(des, name=temp, indexes=()), LITE)[0].sql
    steps: list[tuple[str, tuple[str, ...]]] = [(create, _lost_reviews(cur, des))]
    if any(c.name in {o.name for o in cur.columns} for c in des.columns):
        steps.append((_copy_sql(cur, des, temp), _copy_reviews(cur, des)))
    steps.append((f"DROP TABLE {quote_ident(cur.name)}", ()))
    steps.append((_alter(temp, f"RENAME TO {quote_ident(des.name)}"), ()))
    steps += [(_index_sql(des.name, i), ()) for i in des.indexes]
    return [Change(ALTER_COLUMN, sql, notes, True) for sql, notes in steps]


def _constant_default(default: str) -> bool:
    """Return true when SQLite accepts `default` on `ADD COLUMN` (a constant, not an expression)."""
    return not default.startswith("(") and not default.upper().startswith("CURRENT_")


def _add_in_place(table: Table, col: Column) -> bool:
    """Return true when SQLite can add `col` with `ALTER TABLE ADD COLUMN`."""
    if col.default is None and not col.nullable:
        return False
    if col.default is not None and not _constant_default(col.default):
        return False
    if col.identity or col.name in (table.pk or ()):
        return False
    keyed = [cols for _, cols in table.uniques] + [fk.columns for fk in table.foreign_keys]
    return not any(col.name in cols for cols in keyed)


def _diff_columns(cur: Table, des: Table, dialect: Dialect = PG) -> list[Change]:
    """Return the column changes of a table present on both sides."""
    lite = dialect.name == "sqlite"
    t = cur.name
    old = {c.name: c for c in cur.columns}
    new = {c.name: c for c in des.columns}
    dropped = [c for c in cur.columns if c.name not in new]
    added = [c for c in des.columns if c.name not in old]
    hints = {}
    for gone, came in zip(dropped, added, strict=False):
        hints[gone.name] = hints[came.name] = (
            f"-- possible rename: rewrite as ALTER TABLE {quote_ident(t)} "
            f"RENAME COLUMN {quote_ident(gone.name)} TO {quote_ident(came.name)}"
        )
    out = []
    for c in added:
        notes = () if lite else _not_null_review(t, c)
        notes += _hint(hints, c.name)
        out.append(Change(ADD_COLUMN, _alter(t, f"ADD COLUMN {_column_def(c, dialect)}"), notes))
    for c in des.columns:
        if c.name in old:
            out += [] if lite else _alter_column(t, old[c.name], c)
    for c in dropped:
        why = _review(f"drops column {t}.{c.name}, its data is lost")
        sql = _alter(t, f"DROP COLUMN {quote_ident(c.name)}")
        out.append(Change(DROP_COLUMN, sql, (why, *_hint(hints, c.name))))
    return out


def _not_null_review(table: str, col: Column) -> tuple[str, ...]:
    """Return the review line for a new NOT NULL column that has no default."""
    if col.nullable or col.default is not None or col.identity:
        return ()
    return (_review("NOT NULL column without default fails on a non-empty table"),)


def _hint(hints: dict[str, str], name: str) -> tuple[str, ...]:
    """Return the rename hint of a column, if it has one."""
    return (hints[name],) if name in hints else ()


def _diff_keyed(cur: dict, des: dict, drop, add, kind: int, why: str = "") -> list[Change]:
    """Diff named items: `drop(name)` and `add(item)` give the SQL; `kind` is the add phase.

    `why`, when given, is the review reason put on a drop of an item that is gone from `des`.
    """
    out = []
    for name, item in cur.items():
        if name not in des:
            notes = (_review(why),) if why else ()
            out.append(Change(DROP_FK if kind == ADD_FK else DROP_OTHER, drop(name), notes))
        elif des[name] != item:
            out.append(Change(DROP_CHANGED, drop(name)))
    for name, item in des.items():
        if cur.get(name) != item:
            out.append(Change(kind, add(item)))
    return out


def _diff_pk(cur: Table, des: Table) -> list[Change]:
    """Return the primary key changes of a table."""
    if cur.pk == des.pk:
        return []
    out = []
    if cur.pk is not None:
        name = cur.pk_name or f"{cur.name}_pkey"
        late = des.pk is None
        why = () if late else (_review(f"primary key of {cur.name} changes"),)
        out.append(Change(DROP_OTHER if late else DROP_CHANGED, _drop_constraint(cur.name, name), why))
    if des.pk is not None:
        out.append(Change(ADD_KEY, _pk_sql(des)))
    return out


def _fk_shape(fk: ForeignKey) -> tuple:
    """Return a foreign key without its name, which SQLite does not keep."""
    return (fk.columns, fk.target_table, fk.target_columns, fk.on_delete.upper())


def _diff_indexes(cur: Table, des: Table) -> list[Change]:
    """Return the index changes of a table."""
    t = cur.name
    return _diff_keyed(
        {i.name: _norm_index(i) for i in cur.indexes},
        {i.name: _norm_index(i) for i in des.indexes},
        lambda n: f"DROP INDEX {quote_ident(n)}",
        lambda i: _index_sql(t, i),
        ADD_INDEX,
        "index not managed by korbase or removed from the models",
    )


def _diff_keys(cur: Table, des: Table, dialect: Dialect = PG) -> list[Change]:
    """Return the key, unique and index changes of a table present on both sides."""
    if dialect.name == "sqlite":
        return _diff_indexes(cur, des)
    t = cur.name
    out = _diff_pk(cur, des)
    out += _diff_uniques(cur, des)
    out += _diff_keyed(
        {f.name: f for f in cur.foreign_keys},
        {f.name: f for f in des.foreign_keys},
        lambda n: _drop_constraint(t, n),
        lambda f: _fk_sql(t, f),
        ADD_FK,
    )
    return out + _diff_indexes(cur, des)


def _diff_uniques(cur: Table, des: Table) -> list[Change]:
    """Return the unique constraint changes of a table."""
    t = cur.name
    old, new = dict(cur.uniques), dict(des.uniques)
    out = []
    for name, cols in old.items():
        if name not in new:
            out.append(Change(DROP_OTHER, _drop_constraint(t, name)))
        elif new[name] != cols:
            out.append(Change(DROP_CHANGED, _drop_constraint(t, name)))
    for name, cols in new.items():
        if old.get(name) != cols:
            out.append(Change(ADD_KEY, _unique_sql(t, name, cols)))
    return out


def _pk_dependents(current: Snapshot, desired: Snapshot) -> list[Change]:
    """Return the changes that drop, and re-add, the foreign keys held up by a primary key change."""
    out: list[Change] = []
    for name, cur in current.tables.items():
        des = desired.tables.get(name)
        if cur.pk is None or des is None or des.pk == cur.pk:
            continue
        for src in current.tables.values():
            for fk in src.foreign_keys:
                if fk.target_table != name:
                    continue
                out.append(Change(DROP_DEPENDENT_FK, _drop_constraint(src.name, fk.name)))
                kept = desired.tables.get(src.name)
                if kept is not None and fk in kept.foreign_keys:
                    out.append(Change(ADD_FK, _fk_sql(src.name, fk)))
    return out


def diff(current: Snapshot, desired: Snapshot, dialect: Dialect = PG) -> list[Change]:
    """Return the changes that turn `current` into `desired`, in a safe order."""
    out: list[Change] = []
    for name in sorted(set(current.tables) | set(desired.tables)):
        cur, des = current.tables.get(name), desired.tables.get(name)
        if cur is None and des is not None:
            out += _create_table(des, dialect)
        elif des is None and cur is not None:
            out += _drop_table(cur, dialect)
        elif cur is not None and des is not None and dialect.name == "sqlite" and _rebuild_needed(cur, des):
            out += _rebuild_table(cur, des)
        elif cur is not None and des is not None:
            out += _diff_columns(cur, des, dialect) + _diff_keys(cur, des, dialect)
    if dialect.name != "sqlite":
        out += _pk_dependents(current, desired)
    seen: set[str] = set()
    ordered = sorted(out, key=lambda c: c.phase)
    return [c for c in ordered if not ((k := c.sql or "\n".join(c.comments)) in seen or seen.add(k))]


_SET_STRINGS = "SET standard_conforming_strings = on;\n"


_REBUILD_OPEN = "-- korbase:no-transaction\nPRAGMA foreign_keys=OFF;\nBEGIN IMMEDIATE;\n"
_REBUILD_CLOSE = "PRAGMA foreign_key_check;\nCOMMIT;\nPRAGMA foreign_keys=ON;\n"


def render(changes: list[Change], dialect: Dialect = PG) -> str:
    """Return the SQL file body for `changes`.

    On Postgres it starts with `SET standard_conforming_strings = on;`. Comment lines come before each
    statement, which ends in `;`. On SQLite, when a table is rebuilt, the whole body runs outside
    korbase's transaction (first line `-- korbase:no-transaction`), between `PRAGMA foreign_keys=OFF`
    and `ON`, in its own `BEGIN IMMEDIATE` ... `COMMIT`, with a `PRAGMA foreign_key_check` before the commit.
    """
    if not changes:
        return ""
    body = "".join("".join(f"{c}\n" for c in ch.comments) + (ch.sql + ";\n" if ch.sql else "") for ch in changes)
    if dialect.name != "sqlite":
        return _SET_STRINGS + body
    return _REBUILD_OPEN + body + _REBUILD_CLOSE if any(ch.rebuild for ch in changes) else body
